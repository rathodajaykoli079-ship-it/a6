      <div class="faq-item">
        <button class="faq-question" onclick="this.parentElement.classList.toggle('open');">
          <span>How do RibKnitCairn socks eliminate hiking blisters?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Blisters occur due to shear friction and moisture softening epidermal layers. By combining an anatomical 360-degree arch compression band that locks the sock firmly against your foot, true seamless hand-linked toes that remove rubbing ridges, and merino wool that pulls moisture away in vapor form before liquid sweat pools, our socks halt friction at the source.
        </div>
      </div>

      <div class="faq-item">
        <button class="faq-question" onclick="this.parentElement.classList.toggle('open');">
          <span>Will these 100% merino socks shrink during machine washing?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Our yarns are pre-relaxed and knitted with reinforced dual-ply twisted nylon cores. We recommend cool gentle cycle washing or hand rinsing with mild wool detergent, followed by flat air drying. Avoid high heat tumble dryers, which can cause fiber felting and dimensional compaction.
        </div>
      </div>

      <div class="faq-item">
        <button class="faq-question" onclick="this.parentElement.svg;">
          <span>What is the difference between 18.5-micron and 23-micron wool?</span>
          <span>+</span>
        </button>
        <div class="faq-answer">
          Microns measure individual wool fiber diameter. An 18.5-micron fiber is ultra-soft and bends readily when touching the skin, guaranteeing zero prickle or itchiness. A 23-micron fiber offers higher spring resilience and crush resistance under heavy multi-day expedition packs, making it perfect for high-loft terry footbeds.
        </div>
